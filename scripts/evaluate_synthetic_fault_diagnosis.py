"""Evaluate synthetic sensor-fault recognition on engine-disjoint trajectories.

All fault labels are generated by this project. They are not NASA labels and do
not represent verified physical component failures.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd
from sklearn.metrics import classification_report, confusion_matrix, f1_score

from src.cmapss_data import (
    FEATURE_COLUMNS,
    add_train_rul,
    constant_columns,
    fit_feature_scaler,
    load_telemetry,
    split_engine_units,
    summarize_windows,
    transform_features,
)
from src.diagnosis import compute_calibration_metrics
from src.fault_injection import (
    SYNTHETIC_FAULT_LABELS,
    SYNTHETIC_SENSOR_FAULTS,
    inject_sensor_fault,
)
from src.synthetic_fault_diagnosis import SyntheticSensorFaultAgent


SEED = 42
WINDOW_SIZE = 30
MILESTONES = (30, 60, 90, 120)
BOOTSTRAP_REPLICATES = 10_000


def _extract_windows(
    frame: pd.DataFrame, feature_columns: list[str]
) -> list[tuple[int, int, np.ndarray]]:
    samples: list[tuple[int, int, np.ndarray]] = []
    for unit_id, unit_frame in frame.groupby("unit_id", sort=True):
        unit_frame = unit_frame.sort_values("cycle")
        cycles = unit_frame["cycle"].to_numpy(dtype=int)
        values = unit_frame[feature_columns].to_numpy(dtype=np.float32)
        for cycle in MILESTONES:
            matches = np.flatnonzero(cycles == cycle)
            if not len(matches):
                continue
            end = int(matches[0])
            if end + 1 < WINDOW_SIZE:
                continue
            samples.append(
                (
                    int(unit_id),
                    int(cycle),
                    values[end - WINDOW_SIZE + 1 : end + 1].copy(),
                )
            )
    return samples


def _synthetic_dataset(
    samples: list[tuple[int, int, np.ndarray]],
    feature_columns: list[str],
    seed: int,
    severity_range: tuple[float, float],
) -> tuple[np.ndarray, np.ndarray, np.ndarray, list[dict[str, Any]]]:
    rng = np.random.default_rng(seed)
    windows: list[np.ndarray] = []
    labels: list[str] = []
    units: list[int] = []
    provenance: list[dict[str, Any]] = []
    feature_names = [
        f"{stat}_{feature}"
        for stat in ("last", "mean", "std", "min", "max", "slope")
        for feature in feature_columns
    ]
    feature_names.extend(
        f"{stat}_{feature}"
        for stat in (
            "diff_mean",
            "diff_std",
            "diff_max_abs",
            "flat_fraction",
            "detrended_peak",
        )
        for feature in feature_columns
    )

    for unit_id, cycle, base_window in samples:
        scenarios = [("normal", base_window, {"fault_type": "normal"})]
        for fault_type in SYNTHETIC_SENSOR_FAULTS:
            severity = float(rng.uniform(*severity_range))
            corrupted, details = inject_sensor_fault(
                base_window,
                feature_columns,
                fault_type,
                rng=rng,
                severity=severity,
            )
            scenarios.append((fault_type, corrupted, details))
        for label, window, details in scenarios:
            windows.append(window)
            labels.append(label)
            units.append(unit_id)
            provenance.append(
                {
                    "unit_id": unit_id,
                    "cycle": cycle,
                    "label": label,
                    **details,
                }
            )

    window_array = np.stack(windows).astype(np.float32)
    feature_matrix = summarize_windows(window_array)
    differences = np.diff(window_array, axis=1)
    time_axis = np.arange(window_array.shape[1], dtype=np.float32)
    centered_time = time_axis - time_axis.mean()
    denominator = float(np.sum(centered_time**2))
    slopes = np.einsum(
        "t,ntf->nf", centered_time, window_array - window_array.mean(axis=1, keepdims=True)
    ) / denominator
    intercepts = window_array.mean(axis=1) - slopes * time_axis.mean()
    linear_fit = intercepts[:, None, :] + slopes[:, None, :] * time_axis[None, :, None]
    detrended_peak = np.max(np.abs(window_array - linear_fit), axis=1)
    extra = np.concatenate(
        [
            differences.mean(axis=1),
            differences.std(axis=1),
            np.max(np.abs(differences), axis=1),
            np.mean(np.abs(differences) <= 1e-6, axis=1),
            detrended_peak,
        ],
        axis=1,
    ).astype(np.float32)
    feature_matrix = np.concatenate([feature_matrix, extra], axis=1)
    if feature_matrix.shape[1] != len(feature_names):
        raise RuntimeError("synthetic diagnosis feature names do not align")
    return (
        feature_matrix,
        np.asarray(labels, dtype=str),
        np.asarray(units, dtype=int),
        provenance,
    )


def _evaluate_subset(subset: str) -> tuple[dict[str, Any], pd.DataFrame]:
    data_dir = ROOT / "data" / "raw" / "cmapss"
    full = add_train_rul(load_telemetry(data_dir, subset, "train"))
    split = split_engine_units(full, validation_fraction=0.2, seed=SEED)
    train = full[full["unit_id"].isin(split.train_units)].copy()
    heldout = full[full["unit_id"].isin(split.validation_units)].copy()
    dropped = constant_columns(train, FEATURE_COLUMNS)
    features = [name for name in FEATURE_COLUMNS if name not in dropped]
    sensors = [name for name in features if name.startswith("sensor_")]
    if not sensors:
        raise ValueError("No sensor columns are available for fault injection")

    scaler = fit_feature_scaler(train, features)
    train_scaled = transform_features(train, features, scaler)
    heldout_scaled = transform_features(heldout, features, scaler)
    fit_windows = _extract_windows(train_scaled, features)
    eval_windows = _extract_windows(heldout_scaled, features)
    train_x, train_y, train_groups, _ = _synthetic_dataset(
        fit_windows, features, SEED + 10, (1.5, 2.5)
    )
    eval_x, eval_y, eval_groups, _ = _synthetic_dataset(
        eval_windows, features, SEED + 20, (1.0, 3.0)
    )
    names = [
        f"{stat}_{feature}"
        for stat in (
            "last",
            "mean",
            "std",
            "min",
            "max",
            "slope",
            "diff_mean",
            "diff_std",
            "diff_max_abs",
            "flat_fraction",
            "detrended_peak",
        )
        for feature in features
    ]
    agent = SyntheticSensorFaultAgent.fit(
        train_x,
        train_y,
        feature_names=names,
        n_estimators=200,
        random_state=SEED,
    )
    probabilities = agent.predict_proba(eval_x)
    predicted = probabilities.to_numpy().argmax(axis=1)
    predicted_labels = np.asarray(probabilities.columns, dtype=object)[predicted]
    per_class = classification_report(
        eval_y,
        predicted_labels,
        labels=list(SYNTHETIC_FAULT_LABELS),
        output_dict=True,
        zero_division=0,
    )
    sample_metrics = compute_calibration_metrics(
        eval_y,
        probabilities,
        classes=SYNTHETIC_FAULT_LABELS,
    )
    rows = pd.DataFrame(
        {
            "unit_id": eval_groups,
            "actual_synthetic_label": eval_y,
            "predicted_synthetic_label": predicted_labels,
            "correct": eval_y == predicted_labels,
            "confidence": probabilities.max(axis=1).to_numpy(dtype=float),
        }
    )
    engine_accuracy = rows.groupby("unit_id", sort=True)["correct"].mean()
    rng = np.random.default_rng(SEED + 30)
    boot = rng.integers(
        0, len(engine_accuracy), size=(BOOTSTRAP_REPLICATES, len(engine_accuracy))
    )
    accuracy_draws = engine_accuracy.to_numpy(dtype=float)[boot].mean(axis=1)
    report = {
        "subset": subset,
        "label_scope": "synthetic sensor-level corruptions only; not physical fault labels",
        "official_test_files_loaded": False,
        "protocol": {
            "engine_split": "80% fit / 20% held-out engine evaluation",
            "fit_engine_ids": list(split.train_units),
            "evaluation_engine_ids": list(split.validation_units),
            "milestones_cycles": list(MILESTONES),
            "window_size": WINDOW_SIZE,
            "sensor_columns_eligible_for_injection": sensors,
            "synthetic_classes": list(SYNTHETIC_FAULT_LABELS),
            "fit_severity_range_in_standardized_units": [1.5, 2.5],
            "evaluation_severity_range_in_standardized_units": [1.0, 3.0],
            "training_example_count": int(len(train_y)),
            "evaluation_example_count": int(len(eval_y)),
            "fit_engines_with_windows": int(len(set(train_groups.tolist()))),
            "evaluation_engines_with_windows": int(len(set(eval_groups.tolist()))),
            "features_fit_scope": "Sensor scalers are fitted on fit engines only.",
            "model": {
                "type": "RandomForestClassifier",
                "n_estimators": 200,
                "class_weight": "balanced_subsample",
            },
        },
        "metrics": {
            "accuracy": float(np.mean(eval_y == predicted_labels)),
            "engine_macro_accuracy": float(engine_accuracy.mean()),
            "engine_cluster_bootstrap_95_ci_accuracy": [
                float(np.quantile(accuracy_draws, 0.025)),
                float(np.quantile(accuracy_draws, 0.975)),
            ],
            "macro_f1": float(
                f1_score(
                    eval_y,
                    predicted_labels,
                    labels=list(SYNTHETIC_FAULT_LABELS),
                    average="macro",
                    zero_division=0,
                )
            ),
            "brier_score": sample_metrics["brier_score"],
            "expected_calibration_error": sample_metrics[
                "expected_calibration_error"
            ],
            "per_class": per_class,
            "confusion_matrix_labels_rows_actual_columns_predicted": confusion_matrix(
                eval_y,
                predicted_labels,
                labels=list(SYNTHETIC_FAULT_LABELS),
            ).tolist(),
        },
        "limitations": [
            "The classifier recognizes only project-generated signal perturbations; this does not demonstrate detection of real engine faults.",
            "Evaluation uses held-out engine identities but synthetic labels are generated by the same documented fault mechanisms used for training.",
            "Severity robustness is tested over a broader range, but sensors and perturbation equations remain synthetic assumptions.",
        ],
    }
    return report, rows


def main() -> None:
    reports: dict[str, Any] = {}
    results: list[pd.DataFrame] = []
    for subset in ("FD001", "FD004"):
        report, rows = _evaluate_subset(subset)
        reports[subset] = report
        results.append(rows.assign(subset=subset))
        print(
            f"{subset}: synthetic sensor fault accuracy="
            f"{report['metrics']['accuracy']:.3f}, "
            f"macro-F1={report['metrics']['macro_f1']:.3f}, "
            f"engine-CI={report['metrics']['engine_cluster_bootstrap_95_ci_accuracy']}"
        )
    aggregate = {
        "experiment": "engine-disjoint synthetic sensor fault diagnosis",
        "datasets": reports,
    }
    out_dir = ROOT / "reports" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "synthetic_fault_diagnosis.json"
    csv_path = out_dir / "synthetic_fault_diagnosis_predictions.csv"
    json_path.write_text(
        json.dumps(aggregate, indent=2, allow_nan=False) + "\n", encoding="utf-8"
    )
    pd.concat(results, ignore_index=True).to_csv(csv_path, index=False)
    print(f"JSON report: {json_path.relative_to(ROOT)}")
    print(f"Prediction rows: {csv_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
